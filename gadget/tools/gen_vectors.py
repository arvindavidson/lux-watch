#!/usr/bin/env python3
"""Generate the Noise / framing test vectors from Meta's muse-gadget-sdk.

Runs the SDK's own Python implementation (linux/src/musegadget/noise) with
fixed keys and writes the JSON files that Verify.kt checks against:

    python3 gadget/tools/gen_vectors.py /path/to/muse-gadget-sdk

The BLE pairing vectors are not generated: the SDK ships official ones
(linux/tests/vectors/link_pairing_v5.json), copied into the test resources.
Needs `cryptography` (the SDK's only dependency for this code).
"""

import json
import sys
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import x25519

sdk = Path(sys.argv[1]).resolve()
sys.path.insert(0, str(sdk / "linux" / "src"))

from musegadget.noise import envelope, framing, noise_xx  # noqa: E402
from musegadget.noise._proto import encode_varint, int64_field  # noqa: E402

# Fixed X25519 private keys, in the order the SDK draws them during an XX
# handshake: initiator e, responder e, responder s, initiator s. Verify.kt
# hard-codes the initiator's two (11.. and 44..).
FIXED_KEYS = [bytes([b]) * 32 for b in (0x11, 0x22, 0x33, 0x44)]


def _fixed_key_pairs():
    for raw in FIXED_KEYS:
        priv = x25519.X25519PrivateKey.from_private_bytes(raw)
        pub = priv.public_key().public_bytes(
            encoding=serialization.Encoding.Raw, format=serialization.PublicFormat.Raw
        )
        yield noise_xx._X25519KeyPair(private_key=priv, public_key_bytes=pub)


keys = _fixed_key_pairs()
noise_xx._generate_x25519_key_pair = lambda: next(keys)

init = noise_xx.NoiseXXInitiator()
resp = noise_xx.NoiseXXResponder()
init.initialize()
resp.initialize()
msg1 = init.write_message1()
msg2 = resp.read_message1_and_write_message2(msg1)
init.read_message2(msg2)
msg3 = init.write_message3()
resp.read_message3(msg3)
c1, _ = init.split()
transport_ct = c1.encrypt_with_ad(b"", b"hello-noise-test")
assert next(keys, None) is None, "handshake drew an unexpected number of keys"

request = envelope.ApplicationRequest(
    verb="POST",
    path="/chat/stream",
    headers=[envelope.Header(key="Content-Type", value="application/json")],
    body=b'{"message":"hi"}',
    end_body=True,
)
service_frame = envelope.encode_service_frame(envelope.ServiceFrame.request(1, request))
chunks = framing.encode_noise_frames(service_frame, chunk_id=0x123456789ABCDEF)

out = Path(__file__).resolve().parent.parent / "src" / "test" / "resources"
note = (
    "Generated by gadget/tools/gen_vectors.py from facebookincubator/muse-gadget-sdk "
    "(Apache-2.0). Synthetic fixed keys only."
)
(out / "noise_vectors.json").write_text(json.dumps({
    "note": note,
    "msg1": msg1.hex(),
    "msg2": msg2.hex(),
    "msg3": msg3.hex(),
    "transport_ct": transport_ct.hex(),
}, indent=2) + "\n")
(out / "framing_vectors.json").write_text(json.dumps({
    "note": note,
    "varint_1": encode_varint(1).hex(),
    "varint_300": encode_varint(300).hex(),
    "int64_neg1": int64_field(1, -1).hex(),
    "service_frame": service_frame.hex(),
    "chunks": [c.hex() for c in chunks],
}, indent=2) + "\n")
print(f"wrote {out}/noise_vectors.json, framing_vectors.json")
